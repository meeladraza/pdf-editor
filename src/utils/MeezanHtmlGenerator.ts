const parseAmount = (val: string | number | undefined) => {
  if (!val && val !== 0) return 0;
  const s = typeof val === 'number' ? String(val) : (val || '').toString();
  const n = parseFloat(s.replace(/,/g, '').replace(/[^0-9.\-]/g, ''));
  return isNaN(n) ? 0 : n;
};

const toDDMMYY = (input?: string) => {
  if (!input) return '';
  const s = input.trim();
  // Match formats like 20-OCT-2025 produced by formatDate
  const m = s.match(/^(\d{1,2})-([A-Z]{3})-(\d{4})$/i);
  if (m) {
    const day = m[1].padStart(2, '0');
    const mon = m[2].toUpperCase();
    const map: Record<string,string> = {JAN:'01',FEB:'02',MAR:'03',APR:'04',MAY:'05',JUN:'06',JUL:'07',AUG:'08',SEP:'09',OCT:'10',NOV:'11',DEC:'12'};
    const mm = map[mon] || '01';
    const yy = m[3].slice(-2);
    return `${day}/${mm}/${yy}`;
  }

  // Match dd/mm/yyyy or dd-mm-yyyy
  const m2 = s.match(/^(\d{1,2})[\/\-](\d{1,2})[\/\-](\d{2,4})$/);
  if (m2) {
    const day = m2[1].padStart(2,'0');
    const mm = m2[2].padStart(2,'0');
    const yy = m2[3].length === 4 ? m2[3].slice(-2) : m2[3];
    return `${day}/${mm}/${yy}`;
  }

  // Fallback: try Date parse
  const d = new Date(s);
  if (!isNaN(d.getTime())) {
    const day = String(d.getDate()).padStart(2,'0');
    const mm = String(d.getMonth()+1).padStart(2,'0');
    const yy = String(d.getFullYear()).slice(-2);
    return `${day}/${mm}/${yy}`;
  }

  return s;
};

