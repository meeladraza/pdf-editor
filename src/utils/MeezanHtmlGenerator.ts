const generateSummarySection = (transactions: TransactionRow[], closingBalance: number) => {
  let totalDebit = 0;
  let totalCredit = 0;
  let debitCount = 0;
  let creditCount = 0;

  transactions.forEach((tx) => {
    if (!tx.isOpeningBalance && !tx.isClosingBalance) {
      if (tx.debit) {
        const val =
          typeof tx.debit === "string"
            ? parseFloat(tx.debit.replace(/,/g, ""))
            : tx.debit;
        if (!isNaN(val)) {
          totalDebit += Math.abs(val);
          debitCount++;
        }
      }
      if (tx.credit) {
        const val =
          typeof tx.credit === "string"
            ? parseFloat(tx.credit.replace(/,/g, ""))
            : tx.credit;
        if (!isNaN(val)) {
          totalCredit += Math.abs(val);
          creditCount++;
        }
      }
    }
  });

  return `
    <div style="margin-top: 4px; font-size: 6pt; color: #B21500; font-weight: 600;">
    <div style="display: flex; justify-content: space-between; margin-bottom: 8px;">
    <span><= C L O S I N G - B A L A N C E =></span>
     <span style="padding-right: 100pt;">${formatNumber(closingBalance)}</span>
    </div>
    <div style="display: flex; gap: 3px; margin-bottom: 1px;">
    <div style="width: 28.5%; height: 1px; background-color: #B21500;"></div>
    <div style="width: 28.5%; height: 1px; background-color: #B21500;"></div>
    <div style="width: 28.5%; height: 1px; background-color: #B21500;"></div>
    </div>
      <div style="display: flex; margin-bottom: 1px;">
        <div>Total No. of Credit Transaction</div>
        <div>________________________________________________________</div>
        <div style="margin-left: 2px;">${creditCount}</div>
      </div>
      <div style="display: flex; margin-bottom: 1px;">
        <div>Total No. of Debit Transaction</div>
        <div>________________________________________________________</div>
        <div style="margin-left: 2px;">${debitCount}</div>
      </div>
      <div style="display: flex; margin-bottom: 1px;">
        <div>Total Credit Turnover</div>
        <div>_______________________________________________________________</div>
        <div style="margin-left: 2px;">${formatNumber(totalCredit)}</div>
      </div>
      <div style="display: flex; margin-bottom: 1px;">
        <div>Total Debit Turnover</div>
        <div>_______________________________________________________________</div>
        <div style="margin-left: 2px;">${formatNumber(totalDebit)}</div>
      </div>
    </div>
  `;
};

