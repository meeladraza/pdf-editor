export const generateMeezanHTML = (
  transactions: TransactionRow[],
  accountInfo: MeezanAccountInfo,
): string => {
  const tableHeader = generateTableHeader();
  // Determine opening balance (prefer accountInfo.openingBalance, fallback to opening tx)
  let openingBalance = 0;
  const openingTx = transactions.find((t) => t.isOpeningBalance);
  if (accountInfo.openingBalance) {
    openingBalance = parseAmount(accountInfo.openingBalance);
  } else if (openingTx && openingTx.balance) {
    openingBalance = parseAmount(openingTx.balance);
  }

  // prepare to compute running balance
  let currentBalance = openingBalance;

  // find last normal transaction index (exclude opening/closing)
  const normalIndexes: number[] = [];
  transactions.forEach((t, idx) => {
    if (!t.isOpeningBalance && !t.isClosingBalance) normalIndexes.push(idx);
  });
  const lastNormalIndex = normalIndexes.length ? normalIndexes[normalIndexes.length - 1] : -1;

  let tableRows = "";
  transactions.forEach((tx, idx) => {
    if (tx.isOpeningBalance) {
      const ob = openingBalance || parseAmount(tx.balance);
      currentBalance = ob;
      tableRows += `
        <tr>
          <td colspan="6" style="font-size: 8.5pt; font-weight: 600; padding: 8px 2px; color: #B21500;">&lt;= O P E N I N G - B A L A N C E =&gt;</td>
          <td style="text-align: right; font-size: 8.5pt; font-weight: 600; padding: 8px 2px; color: #000;">${formatNumber(currentBalance)}</td>
          <td></td>
        </tr>
      `;
      return;
    }

    if (tx.isClosingBalance) {
      tableRows += `
        <tr>
          <td colspan="7" style="text-align: right; font-size: 8.5pt; font-weight: 600; padding: 8px 2px; color: #000;">${formatNumber(currentBalance)}</td>
        </tr>
        <tr>
          <td colspan="6" style="font-size: 8.5pt; font-weight: 600; padding: 8px 2px; color: #B21500;">&lt;= C L O S I N G - B A L A N C E =&gt;</td>
          <td style="text-align: right; font-size: 8.5pt; font-weight: 600; padding: 8px 2px; color: #B21500;">${formatNumber(currentBalance)}</td>
          <td></td>
        </tr>
      `;
      return;
    }

    // normal transaction: update running balance
    const debit = parseAmount(tx.debit);
    const credit = parseAmount(tx.credit);
    currentBalance = currentBalance - debit + credit;

    const showBalance = idx === lastNormalIndex;
    tableRows += generateNormalRow(tx, showBalance, currentBalance);
  });

  const styles = `
    @page { 
      size: A4; 
      margin: 1cm; 
    }
    @media print {
      body { margin: 0; padding: 0; background: #fff; }
      .page-break { page-break-after: always; }
      tr { page-break-inside: avoid; }
      thead { display: table-header-group; }
    }
    body { 
      font-family: Arial, sans-serif;
      margin: 0;
      padding: 0;
      background-color: #fff;
      color: #000;
    }
    .container {
      width: 100%;
      max-width: 1000px;
      margin: 0 auto;
      padding: 10px;
    }
    table {
      width: 100%;
      border-collapse: collapse;
      table-layout: fixed;
    }
    th, td {
      border: none;
      vertical-align: top;
    }
  `;

  return `
    <!DOCTYPE html>
    <html lang="en">
    <head>
      <meta charset="UTF-8">
      <title>Meezan Bank Statement</title>
      <style>${styles}</style>
    </head>
    <body>
      <div class="container">
        ${generateHeaderSection(accountInfo)}
        <table>
          ${tableHeader}
          <tbody>
            ${tableRows}
          </tbody>
        </table>
        ${generateSummarySection(transactions, currentBalance)}
        ${generateFooter()}
      </div>
    </body>
    </html>
  `;
};
